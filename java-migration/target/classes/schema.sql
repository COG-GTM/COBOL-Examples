CREATE OR REPLACE FUNCTION update_mod_dt()
RETURNS TRIGGER AS $$
BEGIN
    NEW.MOD_DT = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_accounts_mod_dt
    BEFORE UPDATE ON ACCOUNTS
    FOR EACH ROW
    EXECUTE FUNCTION update_mod_dt();
